import { breakIt, type SimOverrides, type ToggleName } from "@eob/engine";
import { aggregate, CRASH_TEST_CONFIGS, verdict, type ConfigReport, type SeedSummary, type CrashTestParams } from "@eob/crash-test";
import { useEffect, useRef, useState } from "react";
import cliResults from "../../../results/crash-test.json";
import { usd } from "./format.js";
import type { RunSpec } from "./scenarios.js";
import type { CrashTestJob } from "./crashTest.worker.js";

/** Smaller than the CLI's default workload so the seed-runs finish in a browser tab. */
const BROWSER_OVERRIDES: SimOverrides = { workload: { messages: 1_000 } };
const PARAMS: CrashTestParams = { p: 0.05, overrides: BROWSER_OVERRIDES };
const SEEDS = 500;
const CHUNK = 20;

type Row = Pick<ConfigReport, "name" | "toggles" | "seeds" | "failed" | "crashes" | "overMicros" | "underMicros" | "violations"> & {
  firstFailingSeed: number | null;
};

export function CrashTestPanel(props: { onReplay: (spec: RunSpec, label: string) => void }) {
  const [progress, setProgress] = useState<{ done: number; total: number } | null>(null);
  const [rows, setRows] = useState<Row[] | null>(null);
  const [ms, setMs] = useState(0);
  const workers = useRef<Worker[]>([]);

  useEffect(() => () => workers.current.forEach((w) => w.terminate()), []);

  function run() {
    workers.current.forEach((w) => w.terminate());
    const n = Math.max(1, Math.min(8, (navigator.hardwareConcurrency || 4) - 1));
    const jobs: CrashTestJob[] = [];
    CRASH_TEST_CONFIGS.forEach((c, config) => {
      for (let s = 1; s <= SEEDS; s += CHUNK) {
        const seeds = Array.from({ length: Math.min(CHUNK, SEEDS - s + 1) }, (_, i) => s + i);
        jobs.push({ job: jobs.length, config, toggles: c.toggles, seeds, params: PARAMS });
      }
    });
    const results: SeedSummary[][] = CRASH_TEST_CONFIGS.map(() => []);
    let next = 0;
    let done = 0;
    const t0 = performance.now();
    setRows(null);
    setProgress({ done: 0, total: jobs.length * CHUNK });
    workers.current = Array.from({ length: n }, () => {
      const w = new Worker(new URL("./crashTest.worker.ts", import.meta.url), { type: "module" });
      const feed = () => {
        if (next < jobs.length) w.postMessage(jobs[next++]);
      };
      w.onmessage = (e: MessageEvent<{ config: number; summaries: SeedSummary[] }>) => {
        results[e.data.config]!.push(...e.data.summaries);
        done += e.data.summaries.length;
        setProgress({ done, total: CRASH_TEST_CONFIGS.length * SEEDS });
        if (done === CRASH_TEST_CONFIGS.length * SEEDS) {
          setMs(performance.now() - t0);
          setRows(
            CRASH_TEST_CONFIGS.map((c, i) => {
              const sorted = results[i]!.sort((a, b) => a.seed - b.seed);
              return { ...aggregate(c, sorted, 0, null), firstFailingSeed: sorted.find((s) => !s.ok)?.seed ?? null };
            }),
          );
          workers.current.forEach((x) => x.terminate());
        } else feed();
      };
      feed();
      return w;
    });
  }

  const replay = (seed: number, toggles: readonly ToggleName[], overrides: SimOverrides, label: string) =>
    props.onReplay(
      { seed, overrides, safeguards: breakIt(...toggles), crashes: [], crashProbability: PARAMS.p },
      label,
    );

  const cli = cliResults as unknown as { seeds: number; p: number; reports: ConfigReport[] };
  return (
    <section className="panel crash-test">
      <h2>Crash test</h2>
      <p>
        {SEEDS} seeds per config, random crashes with p = {PARAMS.p} at every crash point, 1,000-message workloads, in{" "}
        {Math.max(1, Math.min(8, (navigator.hardwareConcurrency || 4) - 1))} Web Workers.
      </p>
      <button className="primary" onClick={run} disabled={progress !== null && progress.done < progress.total}>
        Run {SEEDS * CRASH_TEST_CONFIGS.length} seed-runs
      </button>
      {progress ? (
        <div className="progress">
          <div style={{ width: `${(100 * progress.done) / progress.total}%` }} />
          <span className="mono">
            {progress.done}/{progress.total}
          </span>
        </div>
      ) : null}
      {rows ? (
        <>
          <ResultTable rows={rows} onReplay={(seed, t, label) => replay(seed, t, BROWSER_OVERRIDES, label)} />
          <p className="hint">Finished in {(ms / 1000).toFixed(1)} s.</p>
        </>
      ) : null}
      <h3>CLI run: {cli.seeds.toLocaleString("en-US")} seeds, default 5,000-message workload</h3>
      <ResultTable
        rows={cli.reports.map((r) => ({ ...r, firstFailingSeed: r.firstFailure?.seed ?? null }))}
        onReplay={(seed, t, label) => replay(seed, t, {}, label)}
      />
      <p className="hint">
        Generated by <code className="mono">pnpm crash-test -- --seeds 2000 --p 0.05</code> (results/crash-test.md).
      </p>
    </section>
  );
}

function ResultTable(props: { rows: Row[]; onReplay: (seed: number, toggles: readonly ToggleName[], label: string) => void }) {
  return (
    <table>
      <thead>
        <tr>
          <th>Config</th>
          <th className="num">Failed seeds</th>
          <th className="num">Over-billed</th>
          <th className="num">Under-billed</th>
          <th className="num">Crashes</th>
          <th>Verdict</th>
          <th>First failing seed</th>
        </tr>
      </thead>
      <tbody>
        {props.rows.map((r) => {
          const v = verdict({ ...r, firstFailure: null, dropMismatches: 0, ms: 0 });
          return (
            <tr key={r.name} className={v === "FAIL" ? "bad" : ""}>
              <td className="mono">{r.name}</td>
              <td className="num mono">
                {r.failed}/{r.seeds}
              </td>
              <td className="num mono">{usd(r.overMicros)}</td>
              <td className="num mono">{usd(r.underMicros)}</td>
              <td className="num mono">{r.crashes.toLocaleString("en-US")}</td>
              <td className={v === "pass" ? "good" : "bad-text"}>{v}</td>
              <td>
                {r.firstFailingSeed !== null ? (
                  <button className="link mono" onClick={() => props.onReplay(r.firstFailingSeed!, r.toggles, `${r.name}, seed ${r.firstFailingSeed}`)}>
                    replay seed {r.firstFailingSeed}
                  </button>
                ) : (
                  <span className="muted">none</span>
                )}
              </td>
            </tr>
          );
        })}
      </tbody>
    </table>
  );
}
